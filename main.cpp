#include "SMS.hpp"
#include "NaborSMS.hpp"
#include "Model.hpp"
#include <iostream>
int main()
{
    std::cout << "=== Демонстрация работы классов ===\n\n";
    // =====================================================
    // 1. КОМПОЗИЦИЯ: NaborSMS содержит SMS
    // =====================================================
    std::cout << "--- 1. Композиция: NaborSMS содержит SMS ---\n";
    {
        NaborSMS nabor;
        nabor.dobavitSMS("Купите хлеб", "+79001234567", true);
        nabor.dobavitSMS("Привет, как дела?", "+79007654321", false);
        nabor.dobavitSMS("Выиграйте миллион!", "+79001112233", true);
        nabor.pechat();
        std::cout << "Размер набора: " << nabor.razmer() << "\n";
        // При выходе из блока уничтожится nabor,
        // а вместе с ним — все SMS внутри него
    }
    std::cout << "\n";
    // =====================================================
    // 2. АГРЕГАЦИЯ: Model использует NaborSMS
    // =====================================================
    std::cout << "--- 2. Агрегация: Model использует NaborSMS ---\n";
    // Набор создаём СНАРУЖИ блока модели — он будет жить дольше
    NaborSMS* naborPtr = new NaborSMS();
    naborPtr->dobavitSMS("Скидка 90% только сегодня", "+79009998877", true);
    naborPtr->dobavitSMS("Встреча в 15:00", "+79005554433", false);
    {
        Model model("NaiveBayes");
        model.obuchit(*naborPtr);       // агрегация — использует набор по ссылке
        model.pechat();
        model.predskazat("Купите сейчас!");
        // model уничтожится здесь, а naborPtr — НЕТ
    }
    std::cout << "\n--- После уничтожения модели набор всё ещё жив: ---\n";
    naborPtr->pechat();                 // работает! Набор жив
    delete naborPtr;                    // теперь удаляем набор вручную
    std::cout << "\n";
    // =====================================================
    // 3. ПРОВЕРКА ПРАВИЛА: нельзя обучить на пустом наборе
    // =====================================================
    std::cout << "--- 3. Проверка правила: пустой набор ---\n";
    {
        NaborSMS pustoyNabor;
        Model model("TestModel");
        model.obuchit(pustoyNabor);     // должно выдать ошибку
        model.predskazat("Тест");       // должно выдать ошибку — модель не обучена
    }
    std::cout << "\n";
    // =====================================================
    // 4. ДИНАМИЧЕСКИЙ МАССИВ ОБЪЕКТОВ
    // =====================================================
    std::cout << "--- 4. Динамический массив SMS ---\n";
    {
        SMS* massiv = new SMS[2];
        massiv[0] = SMS("Спам 1", "+7000", true);
        massiv[1] = SMS("Не спам 1", "+7111", false);
        for (int i = 0; i < 2; ++i)
        {
            massiv[i].pechat();
        }
        delete[] massiv;
    }
    std::cout << "\n=== Конец программы ===\n";
    return 0;
}